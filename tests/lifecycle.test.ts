import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, rmSync, writeFileSync, readdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { defaults } from '../src/config.ts';
import { atomicJSON } from '../src/storage.ts';
const piRoot = process.env.PI_SMART_APPROVAL_TEST_PI_ROOT;
test('installed Pi loader + mocked lifecycle integration (no tool execution, model requests or host configuration writes)', { skip: !piRoot }, async t => {
  const root = mkdtempSync(join(tmpdir(), 'approval-lifecycle-')); const previous = process.env.PI_CODING_AGENT_DIR;
  process.env.PI_CODING_AGENT_DIR = join(root, 'agent');
  t.after(() => { if (previous === undefined) delete process.env.PI_CODING_AGENT_DIR; else process.env.PI_CODING_AGENT_DIR = previous; rmSync(root, { recursive: true, force: true }); });
  const cwd = join(root, 'project'); mkdirSync(cwd);
  const { loadExtensions } = await import(pathToFileURL(join(piRoot!, 'dist/core/extensions/loader.js')).href);
  const result = await loadExtensions([resolve('src/index.ts')], cwd);
  assert.deepEqual(result.errors, []); assert.equal(result.extensions.length, 1);
  const extension = result.extensions[0];
  assert.ok(extension.commands.has('pending-approvals')); assert.ok(extension.commands.has('smart-approval'));
  assert.ok(extension.flags.has('smart-approval-hard-override'));
  const notifications: string[] = []; let prompts = 0;
  const ctx: any = { cwd, mode: 'json', hasUI: false, sessionManager: { getSessionId: () => 'fixture-session' }, ui: { notify: (s: string) => notifications.push(s), setStatus: () => {}, select: async () => { prompts++; return 'Deny'; }, confirm: async () => false } };
  const emit = async (name: string, event: any = {}) => {
    let value; for (const fn of extension.handlers.get(name) ?? []) value = await fn(event, ctx); return value;
  };
  await emit('session_start', { reason: 'startup' });
  assert.equal(await emit('tool_call', { toolName: 'read', toolCallId: '1', input: { path: 'README.md' } }), undefined);
  const blocked = await emit('tool_call', { toolName: 'write', toolCallId: '2', input: { path: '.pi/settings.json', content: '{}' } });
  assert.equal(blocked.block, true); assert.equal(JSON.parse(blocked.reason).code, 'INTERACTIVE_REQUIRED'); assert.equal(prompts, 0);
  const nested = await emit('tool_call', { toolName: 'bash', toolCallId: 'parent/1', parentToolCallId: 'parent', input: { command: 'pwd' } }); assert.equal(nested.block, true);
  const user = await emit('user_bash', { command: 'pwd', cwd }); assert.equal(user.result.exitCode, 1);
  const policy = join(root, 'agent/smart-approval/config.json');
  const c = defaults(); c.smart = false; c.timeoutMs = 10; atomicJSON(policy, c);
  ctx.mode = 'tui'; ctx.hasUI = true; ctx.ui.select = async () => new Promise(() => {});
  const expired = await emit('tool_call', { toolName: 'write', input: { path: 'inert.txt', content: 'synthetic-token' } });
  assert.equal(JSON.parse(expired.reason).code, 'APPROVAL_TIMEOUT');
  assert.equal(readdirSync(join(root, 'agent/smart-approval/pending')).length, 1);
  await emit('session_shutdown', { reason: 'reload' });
  assert.equal(JSON.parse((await emit('tool_call', { toolName: 'read', input: { path: 'x' } })).reason).code, 'SECURITY_ENGINE_FAILURE');
  ctx.mode = 'json'; ctx.hasUI = false; await emit('session_start', { reason: 'reload' });
  assert.equal(readdirSync(join(root, 'agent/smart-approval/pending')).length, 1);
  writeFileSync(policy, '{ malformed');
  assert.equal(JSON.parse((await emit('tool_call', { toolName: 'read', input: { path: 'x' } })).reason).code, 'SECURITY_ENGINE_FAILURE');
});
